#!/usr/bin/env python3
"""Generate voice-over WAVs from Tools/vo_manifest.json via the ElevenLabs API.

Usage (from repo root):
    python Tools/generate_vo.py --dry-run       # preview lines + character/credit cost, no API calls
    python Tools/generate_vo.py                 # generate all missing clips
    python Tools/generate_vo.py --only pawn_intro axiom_firewall
    python Tools/generate_vo.py --force         # regenerate even if the WAV already exists

Requires ELEVENLABS_API_KEY in the repo-root .env (or the environment).
Output: Content/Audio/VO/<Character>/VO_<Character>_<id>.wav  (PCM WAV, ready for UE import)

Idempotent: existing WAVs are skipped, so re-running after editing the manifest
only spends credits on new or --force'd lines.
"""

import argparse
import json
import os
import sys
import urllib.request
import urllib.error
import wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "Tools", "vo_manifest.json")
OUT_ROOT = os.path.join(ROOT, "Content", "Audio", "VO")

API_BASE = "https://api.elevenlabs.io/v1/text-to-speech"

# sample rates for the pcm_* output formats we support
PCM_RATES = {"pcm_16000": 16000, "pcm_22050": 22050, "pcm_24000": 24000, "pcm_44100": 44100}


def load_api_key():
    key = os.environ.get("ELEVENLABS_API_KEY")
    if key:
        return key.strip()
    env_path = os.path.join(ROOT, ".env")
    if os.path.exists(env_path):
        with open(env_path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line.startswith("ELEVENLABS_API_KEY="):
                    return line.split("=", 1)[1].strip().strip('"').strip("'")
    return None


def tts(api_key, voice_id, text, model_id, output_format, settings):
    url = f"{API_BASE}/{voice_id}?output_format={output_format}"
    body = json.dumps({
        "text": text,
        "model_id": model_id,
        "voice_settings": settings,
    }).encode("utf-8")
    req = urllib.request.Request(url, data=body, method="POST", headers={
        "xi-api-key": api_key,
        "Content-Type": "application/json",
        "Accept": "audio/wav",
    })
    with urllib.request.urlopen(req, timeout=120) as resp:
        return resp.read()


def write_wav(path, pcm_bytes, sample_rate):
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)  # ElevenLabs pcm_* is 16-bit mono
        w.setframerate(sample_rate)
        w.writeframes(pcm_bytes)


def cpp_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def emit_cpp(manifest):
    """Write the text->clip lookup table compiled into the game (see ChessVoice.cpp)."""
    out = os.path.join(ROOT, "Source", "ChessKids", "Private", "VoiceLineMap.gen.h")
    rows = []
    for line in manifest["lines"]:
        match = line.get("match", line["text"])  # absent -> match the spoken text
        m = f'TEXT("{cpp_escape(match)}")' if match is not None else "nullptr"
        rows.append(f'\t{{ {m}, TEXT("{line["character"]}"), TEXT("{line["id"]}") }},')
    body = (
        "// Generated by Tools/generate_vo.py from Tools/vo_manifest.json - do not hand-edit.\n"
        "// Included by ChessVoice.cpp. Match==nullptr lines are only playable by id.\n"
        "static const FVoiceLineEntry GVoiceLines[] = {\n" + "\n".join(rows) + "\n};\n"
    )
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    print(f"wrote {os.path.relpath(out, ROOT)} ({len(rows)} entries)")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dry-run", action="store_true", help="list what would be generated; no API calls")
    ap.add_argument("--force", action="store_true", help="regenerate clips that already exist")
    ap.add_argument("--only", nargs="*", default=None, help="only these line ids")
    ap.add_argument("--emit-cpp", action="store_true", help="only regenerate Source/.../VoiceLineMap.gen.h")
    args = ap.parse_args()

    with open(MANIFEST, encoding="utf-8") as f:
        manifest = json.load(f)

    if args.emit_cpp:
        emit_cpp(manifest)
        return

    model_id = manifest["model_id"]
    output_format = manifest.get("output_format", "pcm_24000")
    if output_format not in PCM_RATES:
        sys.exit(f"output_format must be one of {list(PCM_RATES)} (got {output_format})")
    sample_rate = PCM_RATES[output_format]
    voices = manifest["voices"]

    lines = manifest["lines"]
    if args.only:
        wanted = set(args.only)
        lines = [l for l in lines if l["id"] in wanted]
        missing = wanted - {l["id"] for l in lines}
        if missing:
            sys.exit(f"unknown line ids: {sorted(missing)}")

    todo, skipped = [], 0
    for line in lines:
        char = line["character"]
        if char not in voices:
            sys.exit(f"line '{line['id']}' uses unknown character '{char}'")
        out_path = os.path.join(OUT_ROOT, char, f"VO_{char}_{line['id']}.wav")
        if os.path.exists(out_path) and not args.force:
            skipped += 1
            continue
        todo.append((line, out_path))

    total_chars = sum(len(l["text"]) for l, _ in todo)
    print(f"{len(todo)} clip(s) to generate, {skipped} already exist (skipped).")
    print(f"~{total_chars} characters -> ~{total_chars} ElevenLabs credits ({model_id})\n")

    if args.dry_run:
        for line, out_path in todo:
            print(f"  [{line['character']:>5}] {line['id']:<22} \"{line['text']}\"")
        return

    if not todo:
        return

    api_key = load_api_key()
    if not api_key:
        sys.exit("No ELEVENLABS_API_KEY found in .env or environment. Add it and re-run.")

    failed = 0
    for i, (line, out_path) in enumerate(todo, 1):
        char = line["character"]
        voice = voices[char]
        print(f"[{i}/{len(todo)}] {line['id']} ({char}) ... ", end="", flush=True)
        try:
            pcm = tts(api_key, voice["voice_id"], line["text"], model_id,
                      output_format, voice.get("settings", {}))
        except urllib.error.HTTPError as e:
            detail = e.read().decode("utf-8", "replace")[:300]
            print(f"FAILED ({e.code}): {detail}")
            failed += 1
            continue
        except Exception as e:  # noqa: BLE001 - report and continue with remaining lines
            print(f"FAILED: {e}")
            failed += 1
            continue
        os.makedirs(os.path.dirname(out_path), exist_ok=True)
        write_wav(out_path, pcm, sample_rate)
        print(f"ok -> {os.path.relpath(out_path, ROOT)}")

    if failed:
        sys.exit(f"\n{failed} clip(s) failed - re-run to retry just those (existing ones are skipped).")
    print("\nAll done. Import Content/Audio/VO into the editor (or just open it - auto-import).")


if __name__ == "__main__":
    main()
